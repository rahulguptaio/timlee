// Package appfactory turns prompts into apps inside the Timlee Bazel workspace.
//
// It owns the workspace directory: creating apps from templates/app, running the
// Copilot CLI inside one app, building it with Bazel, committing every change to
// the workspace's own git repository, and exposing path-confined file and theme
// editing for the web editor. One Copilot run executes at a time; each app is
// also marked busy during a change so editor saves cannot race a run.
package appfactory

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"html"
	"io/fs"
	"log/slog"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"sync"
	"time"
)

// Config locates the workspace and the external tools the factory drives.
type Config struct {
	// Workspace is the absolute path of the Bazel workspace (the directory with MODULE.bazel).
	Workspace string
	// Bazel is the bazel (or bazelisk) executable. Default "bazel".
	Bazel string
	// Copilot is the Copilot CLI executable. Default "copilot".
	Copilot string
	// GH is the GitHub CLI used to read the signed-in account's token. Default "gh".
	GH string
	// CopilotHome isolates the CLI's config so personal plugins and MCP servers
	// are not loaded into app runs. Default <Workspace>/../.local/copilot-home.
	CopilotHome string
	// Model optionally pins the Copilot model.
	Model string
	// MaxAICredits optionally caps AI credits per prompt (passed to --max-ai-credits).
	MaxAICredits string
	// RunTimeout bounds one Copilot run. Default 15 minutes.
	RunTimeout time.Duration
	// BuildTimeout bounds one Bazel build. Default 5 minutes.
	BuildTimeout time.Duration
	Logger       *slog.Logger
}

// Tokens holds per-scheme design-token overrides.
type Tokens struct {
	Light map[string]string `json:"light"`
	Dark  map[string]string `json:"dark"`
}

// App is the metadata stored in apps/<slug>/timlee.json.
type App struct {
	Slug        string `json:"slug"`
	Name        string `json:"name"`
	Description string `json:"description"`
	Font        string `json:"font"`
	Tokens      Tokens `json:"tokens"`
}

// Factory is safe for concurrent use.
//
// Every change to the workspace (create, prompt run, file save, theme save) is
// one operation, and operations run one at a time. That is what makes
// enforceBoundary sound: while a prompt runs, the only commits that can appear
// are the agent's own, so rewinding to the operation's starting commit never
// discards another app's work. Bazel and the shared git index serialize this
// work anyway, so little concurrency is lost.
type Factory struct {
	cfg Config
	log *slog.Logger

	op       sync.Mutex // held for a whole operation
	activeMu sync.Mutex
	active   string // slug of the running operation, for the UI

	binDir string // `bazel info bazel-bin`, resolved on first build (under op)

	Jobs *Jobs
}

// Errors returned to handlers; they map to HTTP statuses.
var (
	ErrNotFound  = errors.New("app not found")
	ErrBusy      = errors.New("another change is being made; try again when it finishes")
	ErrInvalid   = errors.New("invalid request")
	ErrGenerated = errors.New("file is generated by Timlee; use the theme editor")
	// ErrDirty means someone changed the workspace by hand without committing.
	// Every operation ends by reverting changes outside its app, so starting
	// one would silently discard that work.
	ErrDirty = errors.New("the workspace has uncommitted changes")
)

// New validates the workspace layout and returns a Factory.
func New(cfg Config) (*Factory, error) {
	if cfg.Workspace == "" {
		return nil, errors.New("appfactory: Workspace is required")
	}
	ws, err := filepath.Abs(cfg.Workspace)
	if err != nil {
		return nil, err
	}
	cfg.Workspace = ws
	for _, required := range []string{"MODULE.bazel", "templates/app/timlee.json", "packages/design/src/tokens.json"} {
		if _, err := os.Stat(filepath.Join(ws, required)); err != nil {
			return nil, fmt.Errorf("appfactory: workspace is missing %s: %w", required, err)
		}
	}
	if cfg.Bazel == "" {
		cfg.Bazel = "bazel"
	}
	if cfg.Copilot == "" {
		cfg.Copilot = "copilot"
	}
	if cfg.GH == "" {
		cfg.GH = "gh"
	}
	if cfg.CopilotHome == "" {
		cfg.CopilotHome = filepath.Join(filepath.Dir(ws), ".local", "copilot-home")
	}
	if cfg.RunTimeout <= 0 {
		cfg.RunTimeout = 15 * time.Minute
	}
	if cfg.BuildTimeout <= 0 {
		cfg.BuildTimeout = 5 * time.Minute
	}
	if cfg.Logger == nil {
		cfg.Logger = slog.Default()
	}
	if err := os.MkdirAll(filepath.Join(ws, "apps"), 0o755); err != nil {
		return nil, err
	}
	f := &Factory{cfg: cfg, log: cfg.Logger, Jobs: NewJobs()}
	if err := f.ensureRepo(); err != nil {
		return nil, fmt.Errorf("appfactory: workspace repository: %w", err)
	}
	return f, nil
}

// Workspace returns the absolute workspace path.
func (f *Factory) Workspace() string { return f.cfg.Workspace }

var slugPattern = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9-]{0,48}[a-z0-9])?$`)

// ValidSlug reports whether s is a safe app slug (also a Bazel package name).
func ValidSlug(s string) bool { return slugPattern.MatchString(s) }

var nonSlug = regexp.MustCompile(`[^a-z0-9]+`)

// Slugify derives a slug from a display name.
func Slugify(name string) string {
	s := strings.Trim(nonSlug.ReplaceAllString(strings.ToLower(name), "-"), "-")
	if len(s) > 40 {
		s = strings.TrimRight(s[:40], "-")
	}
	if s == "" {
		s = "app"
	}
	return s
}

func (f *Factory) appDir(slug string) string {
	return filepath.Join(f.cfg.Workspace, "apps", slug)
}

// begin claims the workspace for one operation on slug. It fails fast rather
// than queueing, so the UI can say why a change was refused.
func (f *Factory) begin(slug string) (end func(), err error) {
	if !f.op.TryLock() {
		return nil, ErrBusy
	}
	f.activeMu.Lock()
	f.active = slug
	f.activeMu.Unlock()
	end = func() {
		f.activeMu.Lock()
		f.active = ""
		f.activeMu.Unlock()
		f.op.Unlock()
	}
	if err := f.requireClean(); err != nil {
		end()
		return nil, err
	}
	return end, nil
}

// requireClean refuses to start an operation over uncommitted changes. Every
// operation commits its own work, so a dirty tree means a person edited the
// workspace (shared packages, templates, another app) and has not committed.
func (f *Factory) requireClean() error {
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	out, err := f.gitRaw(ctx, "status", "--porcelain=v1", "--untracked-files=all", "--no-renames", "-z")
	if err != nil {
		return err
	}
	var paths []string
	for _, entry := range strings.Split(out, "\x00") {
		if len(entry) > 3 {
			paths = append(paths, entry[3:])
		}
	}
	if len(paths) == 0 {
		return nil
	}
	shown := paths[:min(len(paths), 3)]
	more := ""
	if len(paths) > len(shown) {
		more = fmt.Sprintf(" and %d more", len(paths)-len(shown))
	}
	f.log.Warn("appfactory: refusing to start over uncommitted changes", "paths", paths)
	return fmt.Errorf("%w (%s%s); commit or stash them in the workspace repository first", ErrDirty, strings.Join(shown, ", "), more)
}

// Busy reports whether an operation on the app is in progress.
func (f *Factory) Busy(slug string) bool {
	f.activeMu.Lock()
	defer f.activeMu.Unlock()
	return f.active != "" && f.active == slug
}

// List returns every app, most recently changed first.
func (f *Factory) List() ([]App, error) {
	entries, err := os.ReadDir(filepath.Join(f.cfg.Workspace, "apps"))
	if err != nil {
		return nil, err
	}
	type item struct {
		app App
		mod time.Time
	}
	var items []item
	for _, e := range entries {
		if !e.IsDir() || !ValidSlug(e.Name()) {
			continue
		}
		app, err := f.Get(e.Name())
		if err != nil {
			continue
		}
		info, err := os.Stat(filepath.Join(f.appDir(e.Name()), "timlee.json"))
		if err != nil {
			continue
		}
		items = append(items, item{app, info.ModTime()})
	}
	sort.Slice(items, func(i, j int) bool { return items[i].mod.After(items[j].mod) })
	apps := make([]App, len(items))
	for i, it := range items {
		apps[i] = it.app
	}
	return apps, nil
}

// Get reads one app's metadata.
func (f *Factory) Get(slug string) (App, error) {
	var app App
	if !ValidSlug(slug) {
		return app, ErrNotFound
	}
	raw, err := os.ReadFile(filepath.Join(f.appDir(slug), "timlee.json"))
	if errors.Is(err, fs.ErrNotExist) {
		return app, ErrNotFound
	}
	if err != nil {
		return app, err
	}
	if err := json.Unmarshal(raw, &app); err != nil {
		return app, fmt.Errorf("apps/%s/timlee.json: %w", slug, err)
	}
	app.Slug = slug
	if app.Tokens.Light == nil {
		app.Tokens.Light = map[string]string{}
	}
	if app.Tokens.Dark == nil {
		app.Tokens.Dark = map[string]string{}
	}
	return app, nil
}

const (
	maxNameLen        = 80
	maxDescriptionLen = 300
)

// Create copies templates/app into apps/<slug>, fills in the name and
// description, writes the generated theme files, and commits.
func (f *Factory) Create(ctx context.Context, name, description string) (App, error) {
	name = strings.TrimSpace(name)
	description = strings.TrimSpace(description)
	if name == "" || len([]rune(name)) > maxNameLen || len([]rune(description)) > maxDescriptionLen {
		return App{}, fmt.Errorf("%w: a name is required (up to %d characters); descriptions are limited to %d characters", ErrInvalid, maxNameLen, maxDescriptionLen)
	}
	if description == "" {
		description = name
	}

	end, err := f.begin("")
	if err != nil {
		return App{}, err
	}
	defer end()

	base := Slugify(name)
	slug := base
	for i := 2; ; i++ {
		if _, err := os.Stat(f.appDir(slug)); errors.Is(err, fs.ErrNotExist) {
			break
		}
		slug = fmt.Sprintf("%s-%d", base, i)
	}

	// A half-created app must not linger: it would show in the list, and the
	// next boundary check would treat it as stray files.
	ctx, cancel := detached(ctx)
	defer cancel()
	app, err := f.createApp(ctx, slug, name, description)
	if err != nil {
		_ = os.RemoveAll(f.appDir(slug))
		_, _ = f.gitCmd(ctx, "reset", "-q", "--", "apps/"+slug)
		return App{}, err
	}
	return app, nil
}

func (f *Factory) createApp(ctx context.Context, slug, name, description string) (App, error) {
	if err := f.copyTemplate(slug, name, description); err != nil {
		return App{}, err
	}
	app, err := f.Get(slug)
	if err != nil {
		return App{}, err
	}
	if err := f.writeThemeFiles(app); err != nil {
		return App{}, err
	}
	if _, err := f.commit(ctx, slug, "Create "+slug); err != nil {
		return App{}, err
	}
	return app, nil
}

// detached keeps an operation's bookkeeping (boundary checks, commits) running
// to completion even if the request that started it goes away, so the
// workspace is never left half-changed.
func detached(ctx context.Context) (context.Context, context.CancelFunc) {
	return context.WithTimeout(context.WithoutCancel(ctx), 2*time.Minute)
}

func (f *Factory) copyTemplate(slug, name, description string) error {
	src := filepath.Join(f.cfg.Workspace, "templates", "app")
	dst := f.appDir(slug)
	return filepath.WalkDir(src, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		target := filepath.Join(dst, rel)
		if d.IsDir() {
			if d.Name() == "dist" || d.Name() == "node_modules" {
				return filepath.SkipDir
			}
			return os.MkdirAll(target, 0o755)
		}
		if !d.Type().IsRegular() {
			return nil
		}
		raw, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(target, fillPlaceholders(rel, raw, slug, name, description), 0o644)
	})
}

// fillPlaceholders substitutes __APP_*__ with values escaped for the file type,
// so a name like `<script>` or `{x}` cannot break HTML, JSON, or Svelte markup.
func fillPlaceholders(rel string, raw []byte, slug, name, description string) []byte {
	if !bytes.Contains(raw, []byte("__APP_")) {
		return raw
	}
	escape := func(s string) string { return s }
	switch filepath.Ext(rel) {
	case ".json":
		escape = func(s string) string {
			b, _ := json.Marshal(s)
			return string(b[1 : len(b)-1])
		}
	case ".html":
		escape = html.EscapeString
	case ".svelte":
		escape = func(s string) string {
			return strings.NewReplacer("{", "&#123;", "}", "&#125;").Replace(html.EscapeString(s))
		}
	default:
		// Placeholders only appear in the file types above; anything else keeps them.
		return raw
	}
	return []byte(strings.NewReplacer(
		"__APP_SLUG__", slug,
		"__APP_NAME__", escape(name),
		"__APP_DESCRIPTION__", escape(description),
	).Replace(string(raw)))
}
