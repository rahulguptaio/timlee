package devstack

import (
	"bufio"
	"crypto/rand"
	"encoding/base64"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Development secrets.
//
// They are generated once and reused, because regenerating the session secret
// on every run would sign every developer out on every restart, and
// regenerating the internal token would desync the two services for as long
// as one of them held a cached verification. They are written to a file the
// repository ignores, with owner-only permissions, and are never printed:
// a secret that reaches a terminal reaches a scrollback buffer, a screen
// share and a pasted bug report.

// SecretNames are the values the stack manages on the developer's behalf.
var SecretNames = []string{"SESSION_SECRET", "TIMLEE_INTERNAL_TOKEN"}

// Secrets is a resolved set of development credentials.
type Secrets struct {
	Values map[string]string
	// Created lists the names generated on this run, so the first run can say
	// it made them without revealing what they are.
	Created []string
	Path    string
}

// LoadSecrets reads the secrets file, generating anything missing and
// rewriting the file only when something changed.
func LoadSecrets(path string) (*Secrets, error) {
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return nil, fmt.Errorf("create %s: %w", filepath.Dir(path), err)
	}

	values, err := readEnvFile(path)
	if err != nil {
		return nil, err
	}

	secrets := &Secrets{Values: values, Path: path}
	for _, name := range SecretNames {
		if values[name] != "" {
			continue
		}
		generated, err := randomSecret()
		if err != nil {
			return nil, err
		}
		values[name] = generated
		secrets.Created = append(secrets.Created, name)
	}

	if len(secrets.Created) > 0 {
		if err := writeEnvFile(path, values); err != nil {
			return nil, err
		}
	}
	// Repair permissions even when nothing changed: a file created before
	// this check, or copied in, may be world-readable.
	if err := os.Chmod(path, 0o600); err != nil {
		return nil, fmt.Errorf("secure %s: %w", path, err)
	}
	return secrets, nil
}

func randomSecret() (string, error) {
	buf := make([]byte, 32)
	if _, err := rand.Read(buf); err != nil {
		return "", fmt.Errorf("generate a secret: %w", err)
	}
	return base64.RawURLEncoding.EncodeToString(buf), nil
}

// readEnvFile parses KEY=VALUE lines, ignoring comments and blanks. A missing
// file is not an error: the first run is expected to have none.
func readEnvFile(path string) (map[string]string, error) {
	values := map[string]string{}

	file, err := os.Open(path)
	if err != nil {
		if os.IsNotExist(err) {
			return values, nil
		}
		return nil, fmt.Errorf("read %s: %w", path, err)
	}
	defer file.Close()

	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, value, found := strings.Cut(line, "=")
		if !found {
			continue
		}
		values[strings.TrimSpace(key)] = strings.Trim(strings.TrimSpace(value), `"'`)
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}
	return values, nil
}

// writeEnvFile writes atomically, so an interrupted run cannot leave a
// half-written file that would silently regenerate every secret next time.
func writeEnvFile(path string, values map[string]string) error {
	names := make([]string, 0, len(values))
	for name := range values {
		names = append(names, name)
	}
	sort.Strings(names)

	var body strings.Builder
	body.WriteString("# Timlee local development secrets, generated by timlee-dev.\n")
	body.WriteString("# Local only: never commit this file or paste its contents anywhere.\n\n")
	for _, name := range names {
		body.WriteString(name + "=" + values[name] + "\n")
	}

	temp := path + ".tmp"
	if err := os.WriteFile(temp, []byte(body.String()), 0o600); err != nil {
		return fmt.Errorf("write %s: %w", temp, err)
	}
	if err := os.Rename(temp, path); err != nil {
		_ = os.Remove(temp)
		return fmt.Errorf("replace %s: %w", path, err)
	}
	return nil
}
