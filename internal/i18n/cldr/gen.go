//go:build ignore

// gen.go writes tables.go from a pinned release of cldr-json. Run it with
// `go generate ./internal/i18n/cldr`; it needs network access to
// raw.githubusercontent.com and fails rather than write partial data.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
	"time"
)

// version is the CLDR release: the one Node 22 (ICU 77) and current browsers
// ship, so the server and Intl agree.
const version = "47.0.0"

const base = "https://raw.githubusercontent.com/unicode-org/cldr-json/" + version + "/cldr-json/"

// locales are the formatting locales generated, with the language whose
// plural rules they use.
var locales = []struct{ id, plural string }{
	{"ar", "ar"},
	{"de", "de"},
	{"en-GB", "en"},
	{"fr", "fr"},
	{"ja", "ja"},
}

var categories = []string{"zero", "one", "two", "few", "many", "other"}

var client = &http.Client{Timeout: time.Minute}

func main() {
	log.SetFlags(0)
	log.SetPrefix("cldr/gen: ")

	plurals := fetch("cldr-core/supplemental/plurals.json")
	cardinal := object(plurals, "supplemental", "plurals-type-cardinal")

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by gen.go from CLDR %s (github.com/unicode-org/cldr-json); DO NOT EDIT.\n\n", version)
	fmt.Fprintf(&out, "package cldr\n\n// Version is the CLDR release the tables come from.\nconst Version = %q\n\n", version)
	out.WriteString("// Locales holds each generated formatting locale by its CLDR ID.\nvar Locales = map[string]*Locale{\n")
	for _, loc := range locales {
		writeLocale(&out, loc.id, object(cardinal, loc.plural))
	}
	out.WriteString("}\n")

	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatalf("format: %v", err)
	}
	if err := os.WriteFile("tables.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func writeLocale(w *bytes.Buffer, id string, plural map[string]any) {
	numbers := object(fetch("cldr-numbers-full/main/"+id+"/numbers.json"), "main", id, "numbers")
	usd := object(fetch("cldr-numbers-full/main/"+id+"/currencies.json"), "main", id, "numbers", "currencies", "USD")
	greg := object(fetch("cldr-dates-full/main/"+id+"/ca-gregorian.json"), "main", id, "dates", "calendars", "gregorian")
	fields := object(fetch("cldr-dates-full/main/"+id+"/dateFields.json"), "main", id, "dates", "fields")
	units := object(fetch("cldr-units-full/main/"+id+"/units.json"), "main", id, "units", "short")

	fmt.Fprintf(w, "%q: {\n", id)

	var rules [6]string
	for i, c := range categories[:5] {
		if r, ok := plural["pluralRule-count-"+c].(string); ok {
			cond, _, _ := strings.Cut(r, "@")
			rules[i] = strings.TrimSpace(cond)
		}
	}
	fmt.Fprintf(w, "PluralRules: [Categories]string%s,\n", forms(rules))

	if ns := str(numbers, "defaultNumberingSystem"); ns != "latn" {
		log.Fatalf("%s: default numbering system %q, want latn", id, ns)
	}
	sym := object(numbers, "symbols-numberSystem-latn")
	for _, f := range [][2]string{
		{"Decimal", "decimal"}, {"Group", "group"}, {"PercentSign", "percentSign"}, {"PlusSign", "plusSign"},
		{"MinusSign", "minusSign"}, {"Infinity", "infinity"}, {"NaN", "nan"},
	} {
		fmt.Fprintf(w, "%s: %s,\n", f[0], q(str(sym, f[1])))
	}
	mgd, err := strconv.Atoi(str(numbers, "minimumGroupingDigits"))
	if err != nil {
		log.Fatalf("%s: minimumGroupingDigits: %v", id, err)
	}
	fmt.Fprintf(w, "MinimumGroupingDigits: %d,\n", mgd)

	decimal := object(numbers, "decimalFormats-numberSystem-latn")
	fmt.Fprintf(w, "DecimalPattern: %s,\n", q(str(decimal, "standard")))
	fmt.Fprintf(w, "PercentPattern: %s,\n", q(str(object(numbers, "percentFormats-numberSystem-latn"), "standard")))
	fmt.Fprintf(w, "CurrencyPattern: %s,\n", q(str(object(numbers, "currencyFormats-numberSystem-latn"), "standard")))
	fmt.Fprintf(w, "USD: %s,\n", q(str(usd, "symbol-alt-narrow")))
	writeCompact(w, id, object(decimal, "short", "decimalFormat"))

	months := object(greg, "months", "format", "abbreviated")
	w.WriteString("Months: [12]string{")
	for m := 1; m <= 12; m++ {
		w.WriteString(q(str(months, strconv.Itoa(m))) + ", ")
	}
	w.WriteString("},\n")
	periods := object(greg, "dayPeriods", "format", "abbreviated")
	fmt.Fprintf(w, "AM: %s,\nPM: %s,\n", q(str(periods, "am")), q(str(periods, "pm")))

	available := object(greg, "dateTimeFormats", "availableFormats")
	dateMedium := datePattern(id, str(greg, "dateFormats", "medium"))
	monthDay := datePattern(id, str(available, "MMMd"))
	timeShort := datePattern(id, str(greg, "timeFormats", "short"))
	glue := str(greg, "dateTimeFormats", "medium")
	clock := "Hm"
	if twelveHour(timeShort) {
		clock = "hm"
	}
	// Intl's {hour: "2-digit"} asks for the hour field at width two, and the
	// pattern generator widens the locale's own field to match.
	hour := twoDigitHour(datePattern(id, str(available, clock)))
	fmt.Fprintf(w, "DateMedium: %s,\nMonthDay: %s,\nTimeShort: %s,\n", q(dateMedium), q(monthDay), q(timeShort))
	fmt.Fprintf(w, "DateTimeMedium: %s,\n", q(join(id, glue, dateMedium, timeShort)))
	fmt.Fprintf(w, "MonthDayTime: %s,\n", q(join(id, glue, monthDay, hour)))

	w.WriteString("Relative: [RelativeUnits][2][Categories]string{\n")
	for _, unit := range []string{"second", "minute", "hour", "day"} {
		field := object(fields, unit)
		fmt.Fprintf(w, "{%s, %s},\n",
			forms(patterns(object(field, "relativeTime-type-future"), "relativeTimePattern-count-")),
			forms(patterns(object(field, "relativeTime-type-past"), "relativeTimePattern-count-")))
	}
	w.WriteString("},\n")

	w.WriteString("Units: [DurationUnits][Categories]string{\n")
	for _, unit := range []string{"duration-millisecond", "duration-second", "duration-minute"} {
		fmt.Fprintf(w, "%s,\n", forms(patterns(object(units, unit), "unitPattern-count-")))
	}
	w.WriteString("},\n},\n")
}

// writeCompact writes the compact patterns indexed by magnitude.
func writeCompact(w *bytes.Buffer, id string, short map[string]any) {
	byMagnitude := map[int][6]string{}
	top := 0
	keys := make([]string, 0, len(short))
	for k := range short {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		if strings.Contains(k, "-alt-") {
			continue
		}
		power, category, ok := strings.Cut(k, "-count-")
		if !ok || strings.Trim(power, "0") != "1" {
			log.Fatalf("%s: unexpected compact key %q", id, k)
		}
		c := index(id, category)
		m := len(power) - 1
		f := byMagnitude[m]
		f[c] = short[k].(string)
		byMagnitude[m] = f
		top = max(top, m)
	}
	w.WriteString("Compact: [][Categories]string{\n")
	for m := 0; m <= top; m++ {
		if f, ok := byMagnitude[m]; ok {
			if f[5] == "" {
				log.Fatalf("%s: compact 10^%d has no other form", id, m)
			}
			fmt.Fprintf(w, "%d: %s,\n", m, forms(f))
		}
	}
	w.WriteString("},\n")
}

// patterns collects the plural forms under prefix ("unitPattern-count-").
func patterns(obj map[string]any, prefix string) [6]string {
	var out [6]string
	for k, v := range obj {
		category, ok := strings.CutPrefix(k, prefix)
		if !ok {
			continue
		}
		out[index("", category)] = v.(string)
	}
	if out[5] == "" {
		log.Fatalf("no other form under %s", prefix)
	}
	return out
}

func index(id, category string) int {
	for i, c := range categories {
		if c == category {
			return i
		}
	}
	log.Fatalf("%s: unknown plural category %q", id, category)
	return 0
}

func forms(f [6]string) string {
	parts := make([]string, len(f))
	for i, s := range f {
		parts[i] = q(s)
	}
	return "{" + strings.Join(parts, ", ") + "}"
}

// datePattern rejects a pattern using a field internal/i18n does not format.
func datePattern(id, p string) string {
	quoted := false
	for _, r := range p {
		switch {
		case r == '\'':
			quoted = !quoted
		case quoted:
		case strings.ContainsRune("yMdHhKkma", r):
		case r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z':
			log.Fatalf("%s: pattern %q uses field %q, which internal/i18n does not format", id, p, r)
		}
	}
	return p
}

func twelveHour(p string) bool {
	quoted := false
	for _, r := range p {
		if r == '\'' {
			quoted = !quoted
		} else if !quoted && (r == 'h' || r == 'K') {
			return true
		}
	}
	return false
}

// twoDigitHour widens the pattern's hour field to two digits.
func twoDigitHour(p string) string {
	var b strings.Builder
	quoted := false
	rs := []rune(p)
	for i := 0; i < len(rs); i++ {
		r := rs[i]
		if r == '\'' {
			quoted = !quoted
		}
		if quoted || !strings.ContainsRune("HhKk", r) {
			b.WriteRune(r)
			continue
		}
		for i+1 < len(rs) && rs[i+1] == r {
			i++
		}
		b.WriteString(string(r) + string(r))
	}
	return b.String()
}

// join substitutes a date and a time pattern into a dateTimeFormat. The glue
// must hold no pattern letters, or it would be read as fields.
func join(id, glue, date, clock string) string {
	rest := strings.NewReplacer("{0}", "", "{1}", "").Replace(glue)
	if strings.ContainsAny(rest, "'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ") {
		log.Fatalf("%s: dateTimeFormat %q has literal letters", id, glue)
	}
	return strings.NewReplacer("{1}", date, "{0}", clock).Replace(glue)
}

func q(s string) string { return strconv.Quote(s) }

func fetch(path string) map[string]any {
	resp, err := client.Get(base + path)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("GET %s: %s", path, resp.Status)
	}
	raw, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	var v map[string]any
	if err := json.Unmarshal(raw, &v); err != nil {
		log.Fatalf("%s: %v", path, err)
	}
	return v
}

func object(v map[string]any, path ...string) map[string]any {
	for _, p := range path {
		next, ok := v[p].(map[string]any)
		if !ok {
			log.Fatalf("no object at %q", strings.Join(path, "/"))
		}
		v = next
	}
	return v
}

func str(v map[string]any, path ...string) string {
	last := path[len(path)-1]
	s, ok := object(v, path[:len(path)-1]...)[last].(string)
	if !ok {
		log.Fatalf("no string at %q", strings.Join(path, "/"))
	}
	return s
}
